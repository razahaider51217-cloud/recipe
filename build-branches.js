if (optMarker.test(index)) {
   index = index.replace(optMarker, '                              <!-- BRANCH_OPTIONS_START -->\n' +
      options + '\n                              <!-- BRANCH_OPTIONS_END -->');
   console.log('reservation branch options: updated (' + BRANCHES.length + ')');
} else {
   console.log('WARNING: BRANCH_OPTIONS markers not found - reservation select left untouched');
}

