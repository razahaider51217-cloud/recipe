/* ==========================================================================
   Generates, from branches-data.js:
     1. sarab/js/branches.js      -> window.SARAB_BRANCHES (booking + checkout)
     2. the homepage branch section in sarab/index.html
        (between <!-- BRANCHES_START --> and <!-- BRANCHES_END -->)
     3. the <option> list inside the homepage reservation branch <select>
        (between <!-- BRANCH_OPTIONS_START --> and <!-- BRANCH_OPTIONS_END -->)
     4. sarab/locations.html      -> full branch directory + booking form
   Run: node build-branches.js
   ========================================================================== */
