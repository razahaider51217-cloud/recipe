const marker = /[ \t]*<!-- BRANCHES_START[\s\S]*?<!-- BRANCHES_END -->/;

if (marker.test(index)) {
   index = index.replace(marker, section);
   console.log('homepage branch section: updated');
} else {
   const anchor = '      <!-- RESERVATION FORM -->';
   if (index.indexOf(anchor) === -1) throw new Error('RESERVATION FORM anchor not found in index.html');
   index = index.replace(anchor, section + '\n\n' + anchor);
   console.log('homepage branch section: inserted before the reservation form');
}

