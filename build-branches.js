function mapLink(b) {
   return 'https://www.google.com/maps/search/?api=1&query=' +
      encodeURIComponent(b.street + ', ' + b.city + ', ' + b.state + ' ' + b.zip);
}
function mapEmbed(b) {
   return 'https://www.google.com/maps?q=' +
      encodeURIComponent(b.street + ', ' + b.city + ', ' + b.state + ' ' + b.zip) + '&output=embed';
}

